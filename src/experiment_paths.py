from functools import cached_property
from pathlib import Path
from typing import List

PROJECT_ROOT = (
    Path(__file__).resolve().parent.parent
)  # example: /home/username/rad_analysis/
DATA_FOLDER = PROJECT_ROOT / "data"


class ExperimentPaths:
    """
    Centralized path management.
    """

    def __init__(self, experiment_name: str):
        self.experiment_name = experiment_name
        self.experiment_folderpath = DATA_FOLDER / experiment_name

    @cached_property
    def results_folderpath(self) -> Path:
        # folder where all analysis results are saved (CSVs and plots)
        path = self.experiment_folderpath / "results"
        path.mkdir(parents=True, exist_ok=True)
        return path

    @cached_property
    def logs_folderpath_old(self, device_name: str = "rasp4-coral") -> Path:
        # folder where we find the logs of an experiment
        path = self.experiment_folderpath / "logs" / device_name
        try:
            logs = [f for f in path.iterdir() if f.is_file()]
            if len(logs) == 0:
                print(f"Warning: No files found at {path}")
        except FileNotFoundError:
            print(f"Warning: Logs folder not found at {path}")
        return path

    @cached_property
    def logs_folderpaths(self) -> List[Path]:
        # folder where we find the logs of an experiment
        root_logs_folderpath = self.experiment_folderpath / "logs"
        # get device names
        self.logs_folderpaths = [
            f for f in root_logs_folderpath.iterdir() if f.is_dir()
        ]
        # check if there are log files
        for logs_folder in self.logs_folderpaths:
            try:
                logs = [f for f in logs_folder.iterdir() if f.is_file()]
                if len(logs) == 0:
                    print(f"Warning: No files found at {logs_folder}")
            except FileNotFoundError:
                print(f"Warning: Logs folder not found at {logs_folder}")
        print(f"self.logs_folderpaths: {self.logs_folderpaths}")
        return self.logs_folderpaths

    @cached_property
    def plots_folderpath(self) -> Path:
        # folder where all plot generated by the analysis scripts are saved
        path = self.results_folderpath / "plots"
        path.mkdir(parents=True, exist_ok=True)
        return path

    @cached_property
    def runs_info_csv(self) -> Path:
        # input CSV file with information on when each run started and ended + flux information
        return self.experiment_folderpath / f"{self.experiment_name}_runs_info.csv"

    @cached_property
    def logs_info_csv(self) -> Path:
        # CSV file containing one row per log file, with information retrieved from this log
        return self.results_folderpath / f"{self.experiment_name}_logs_info.csv"

    @cached_property
    def cross_sections_per_run_csv(self) -> Path:
        # CSV file containing the SDC and DUE cross sections for each run (>=1 row per model)
        return (
            self.results_folderpath
            / f"{self.experiment_name}_cross_sections_per_run.csv"
        )

    @cached_property
    def cross_sections_per_model_csv(self) -> Path:
        # CSV file containing the SDC and DUE cross sections for each model
        return (
            self.results_folderpath
            / f"{self.experiment_name}_cross_sections_per_model.csv"
        )

    @cached_property
    def sdcs_csv(self) -> Path:
        # CSV file containing 1 row per SDC
        return self.results_folderpath / f"{self.experiment_name}_SDCs.csv"

    @cached_property
    def sdc_details_csv(self) -> Path:
        # CSV file containing 1 row per each wrong/corrupted element of a SDC (many rows per SDC)
        return self.results_folderpath / f"{self.experiment_name}_SDC_details.csv"


